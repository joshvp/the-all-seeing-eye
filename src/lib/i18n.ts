export type CopyKey = keyof Copy;

export function t(locale: LocaleId, key: CopyKey): string {
  return COPY[locale][key];
}

function fill(template: string, slots: Record<string, string>): string {
  return template.replace(/\{(\w+)\}/g, (_, key: string) => slots[key] ?? "");
}

const POSITION_KEY: Record<string, CopyKey> = {
  past: "past",
  present: "present",
  future: "future",
  heart: "heart",
  cross: "cross",
  root: "root",
  recent: "recent",
  crown: "crown",
  near: "near",
  self: "self",
  house: "house",
  hope: "hope",
  outcome: "line",
  "h-past": "past",
  "h-present": "present",
  "h-hidden": "hidden",
  "h-obstacle": "obstacle",
  "h-field": "field",
  "h-counsel": "counsel",
  "h-line": "line",
  only: "theCard",
  mind: "mind",
  body: "body",
  spirit: "spirit",
  situation: "situation",
  obstacle: "obstacle",
};

export function positionLabel(locale: LocaleId, id: string, family: string): string {
  if (id === "third") return t(locale, family === "counsel" ? "advice" : "outcome");
  const key = POSITION_KEY[id] ?? "theCard";
  return t(locale, key);
}

export function spreadLabel(locale: LocaleId, nameKey: string): string | null {
  if (nameKey === "celtic") return t(locale, "celtic");
  if (nameKey === "horseshoe") return t(locale, "horseshoe");
  if (nameKey === "one") return t(locale, "oneCard");
  if (nameKey === "mind") return t(locale, "mindBody");
  return null;
}

export function leanLine(locale: LocaleId, lean: "Yes" | "No" | "Maybe", name: string, reversed: boolean): string {
  const word = lean === "Yes" ? t(locale, "yes") : lean === "No" ? t(locale, "no") : t(locale, "maybe");
  return fill(t(locale, "lean"), {
    lean: word,
    name,
    rev: reversed ? t(locale, "revClause") : "",
  });
}

export function fallbackVoice(input: {
  locale: LocaleId;
  positions: SpreadPosition[];
  drawn: Drawn[];
  yesNo: boolean;
}): Voice {
  const copy = COPY[input.locale];
  const lines = input.drawn.map((drawn, index) => {
    const position = input.positions[index];
    const name = cardName(input.locale, drawn.card);
    const pos = position ? positionLabel(input.locale, position.id, position.family) : copy.theCard;
    const orient = drawn.reversed ? copy.reversed : copy.upright;
    return {
      position: pos,
      meaning: fill(drawn.reversed ? copy.fallbackDown : copy.fallbackUp, { name }),
      here: fill(copy.fallbackHere, { pos, name, orient }),
    };
  });
  return {
    lines,
    spread: copy.fallbackSpread,
    spoken: lines
      .map((line) => [line.position, line.meaning, line.here].filter(Boolean).join(" "))
      .join(" "),
    ask: copy.fallbackAsk,
    lean: leanOf(input.drawn, input.positions, input.yesNo),
  };
}
